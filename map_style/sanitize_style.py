"""Sanitize a Mapbox Studio style export for publication.

Accepts the zip from Mapbox Studio (Share > Download, or Styles > ... > Download)
or a bare style.json. Writes:

  map_style/style.json      credentials and account metadata removed
  map_style/TILESETS.md     every external source the style depends on

Removes access tokens from all URLs, drops account metadata (owner, created,
modified, visibility, draft, protected), and fails if anything that looks like
a Mapbox token (pk./sk./tk.) survives.

Run:  python map_style/sanitize_style.py path/to/export.zip
"""

from __future__ import annotations

import json
import re
import sys
import zipfile
from pathlib import Path
from urllib.parse import parse_qsl, urlencode, urlsplit, urlunsplit

HERE = Path(__file__).resolve().parent
ACCOUNT_KEYS = {"owner", "created", "modified", "visibility", "draft", "protected"}
TOKEN_PARAMS = {"access_token", "token", "key", "apikey", "api_key"}
TOKEN_RE = re.compile(r"\b[pst]k\.[A-Za-z0-9_\-]{20,}\.[A-Za-z0-9_\-]{10,}")


def load(path: Path) -> dict:
    if path.suffix.lower() == ".zip":
        with zipfile.ZipFile(path) as z:
            name = next(n for n in z.namelist() if n.endswith("style.json"))
            return json.loads(z.read(name))
    return json.loads(path.read_text(encoding="utf-8"))


def strip_tokens(value):
    if isinstance(value, dict):
        return {k: strip_tokens(v) for k, v in value.items()}
    if isinstance(value, list):
        return [strip_tokens(v) for v in value]
    if isinstance(value, str) and ("://" in value or value.startswith("mapbox:")):
        parts = urlsplit(value)
        if parts.query:
            q = [(k, v) for k, v in parse_qsl(parts.query, keep_blank_values=True)
                 if k.lower() not in TOKEN_PARAMS]
            return urlunsplit(parts._replace(query=urlencode(q, safe="{}")))
    return value


def tileset_table(style: dict) -> str:
    layers_by_source: dict[str, list[str]] = {}
    for layer in style.get("layers", []):
        if "source" in layer:
            layers_by_source.setdefault(layer["source"], []).append(layer["id"])
    rows = []
    for name, src in style.get("sources", {}).items():
        url = src.get("url") or ", ".join(src.get("tiles", [])) or ("inline GeoJSON" if src.get("type") == "geojson" else "")
        if url.startswith("mapbox://"):
            ids = url.removeprefix("mapbox://").split(",")
            public = all(i.startswith("mapbox.") for i in ids)
            origin = "Mapbox public tileset" if public else "Account tileset (must be re-created by the user)"
        else:
            origin = "External URL" if url else "Inline"
        rows.append(f"| `{name}` | {src.get('type', '')} | `{url}` | {origin} | "
                    f"{', '.join(f'`{l}`' for l in layers_by_source.get(name, []))} |")
    extras = []
    for key in ("sprite", "glyphs"):
        if key in style:
            extras.append(f"- **{key}**: `{style[key]}`")
    return "\n".join([
        "# Tileset and asset dependencies",
        "",
        "Generated by `sanitize_style.py` from the exported style.",
        "",
        "| Source | Type | URL | Origin | Layers |",
        "|---|---|---|---|---|",
        *rows,
        "",
        *extras,
    ]) + "\n"


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    style = load(Path(sys.argv[1]))
    for k in ACCOUNT_KEYS:
        style.pop(k, None)
    style = strip_tokens(style)
    text = json.dumps(style, indent=2, ensure_ascii=False)
    leaks = TOKEN_RE.findall(text)
    if leaks:
        sys.exit(f"Refusing to write: {len(leaks)} token-like strings remain.")
    (HERE / "style.json").write_text(text + "\n", encoding="utf-8")
    (HERE / "TILESETS.md").write_text(tileset_table(style), encoding="utf-8")
    print(f"Wrote {HERE / 'style.json'} and {HERE / 'TILESETS.md'}")


if __name__ == "__main__":
    main()
